  <li><strong>Step 3 — Revision &amp; Backspace Density:</strong> Verify that the essay exhibits a healthy revision index. Authentic essays typically feature <strong>500 to 2,500+ keystroke deletions/backspaces</strong> as the writer refines tone and syntax.</li>
