<h3>Phase 2: Telemetry Audit &amp; Paste Deconstruction</h3>
<ul>
  <li><strong>Step 1 — Session Volume &amp; Duration:</strong> Check that the essay was drafted across multiple sessions. A genuine Common App personal statement typically reflects <strong>6 to 18 hours of total engagement</strong> across 4 to 12 distinct dates.</li>
