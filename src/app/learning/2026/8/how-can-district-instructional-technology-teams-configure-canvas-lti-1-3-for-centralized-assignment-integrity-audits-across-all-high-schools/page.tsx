  <li><strong>District Liability in Breaches:</strong> If a free browser extension suffers a data breach exposing student essays and student PII, the school district remains legally liable for unauthorized data disclosure under state laws such as New York Education Law &sect; 2-d and Illinois SOPPA.</li>
