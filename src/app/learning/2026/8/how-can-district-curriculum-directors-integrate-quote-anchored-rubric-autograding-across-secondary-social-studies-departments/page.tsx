  <div class="rounded-xl border border-border bg-card p-5 shadow-sm">
    <h3 class="text-base font-bold text-foreground mb-2">2. How does Checkmark distinguish between legitimate outside historical evidence and uncredited copying or document hallucination?</h3>
    <p class="text-xs text-muted-foreground m-0">Checkmark's engine cross-references all historical proper nouns and concepts against both the provided assignment document packet and its comprehensive historical ontology. If a student mentions the <em>Sherman Anti-Trust Act of 1890</em> in a Progressive Era DBQ, Checkmark verifies that the act is not mentioned in Documents 1–7, confirms its chronological accuracy, and verifies that the term is syntactically connected to an argumentative claim. If text matches external online sources without attribution, it is separately flagged in the Plagiarism Breakdown sidebar.</p>
  </div>

