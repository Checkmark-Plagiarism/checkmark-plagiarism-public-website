    <p class="text-xs text-muted-foreground m-0">Yes. Checkmark enforces a strict <strong>Teacher-in-the-Loop</strong> model. No AI evaluation is ever published directly to students or synced to the gradebook without educator authorization. Teachers use the Pre-Flight Educator Review Console to inspect quote cards, adjust criterion scores up or down with a single click, append personalized guidance, or completely rewrite comments before authorizing grade passback.</p>
