      <li><strong>Prepositional errors:</strong> Literal translation of &ldquo;depends on&rdquo; as <em>&ldquo;depende en&rdquo;</em> (direct calque of English &ldquo;on&rdquo;) or clumsy clause structures like <em>&ldquo;trabajar en solucionar el problema&rdquo;</em> instead of <em>&ldquo;esforzarse por solucionar.&rdquo;</em></li>
