<h4>How LLMs Fail FOREX Mechanics:</h4>
<ul>
  <li><strong>The Inverted Inflow Error</strong>: LLMs often state: <em>&ldquo;When the Fed raises interest rates, investors pull their money out of the United States because borrowing is more expensive, causing the dollar to depreciate.&rdquo;</em> In reality, international financial capital seeks higher yields, so global investors demand US assets, causing capital <strong>inflows</strong> and dollar <strong>appreciation</strong>.</li>
