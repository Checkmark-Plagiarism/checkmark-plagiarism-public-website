  <li>Generating <strong>Passive Periphrastics</strong> with <em>sein + zu + Infinitiv</em> (e.g., <em>&ldquo;Es ist zu beachten, dass...&rdquo;</em> instead of <em>&ldquo;Man muss beachten, dass...&rdquo;</em>).</li>
