  <li><strong>Optical / Manual Transcription Telemetry:</strong> Keystroke velocity curves showing robotic, unvarying character input rates (e.g., exactly 65 WPM without pause for 45 continuous minutes), indicating the student was manually retyping text while reading off a secondary mobile device or secondary screen.</li>
