  <li><strong>High Local Revision Rate:</strong> Authentic legal writers constantly revise subordinate clauses, swap adjectives for precise terms of art, and adjust modal verbs (e.g., changing <em>&ldquo;the court must&rdquo;</em> to <em>&ldquo;the court may&rdquo;</em>).</li>
