  <li><strong>Word-Prediction Selection Telemetry:</strong> When using Co:Writer or Read&amp;Write, the telemetry logs 1-to-3 human keystrokes followed by an instant word insertion triggered by a <code>Tab</code>, <code>Enter</code>, or number-key event, occurring at a natural human reaction velocity (400ms–800ms). This captures genuine human decision-making.</li>
